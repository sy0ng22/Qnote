// Calculate day of year from date string (YYYY-MM-DD)
function getDayOfYear(dateString) {
  const date = new Date(dateString);
  const start = new Date(date.getFullYear(), 0, 0);
  const diff = date - start;
  const oneDay = 1000 * 60 * 60 * 24;
  return Math.floor(diff / oneDay);
}

function getQuestionForDate(dateString) {
  const dayOfYearValue = getDayOfYear(dateString);
  // dayOfYear returns 1-366, we need 0-364 for array index
  const index = (dayOfYearValue - 1) % questions.length;
  return questions[index];
}

